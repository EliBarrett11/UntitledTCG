// Generates src/data/cards.js from docs/cards.json (the single source of truth for cards).
// Usage: node tools/buildcards.mjs [--check]
//
// It checks every card against the approved vocabulary (keywords, triggers, effect ops and targets),
// builds each card's wording from the templates in src/engine/wording.js, and writes the card data with
// that generated wording. Card text is never hand-typed in code. --check only verifies that
// src/data/cards.js is up to date (exit 1 if not).
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { KEYWORDS, TRIGGERS, EFFECT_OPS, EFFECT_TARGETS, TARGET_SPECS } from '../src/engine/abilities.js';
import { creatureLines, effectText, heldText, passiveText, questText } from '../src/engine/wording.js';
import { SERIES_RANGE, CAMPAIGN_LENGTHS } from '../src/engine/rules.js';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = join(ROOT, 'docs', 'cards.json');
const OUT = join(ROOT, 'src', 'data', 'cards.js');
const ART_OUT = join(ROOT, 'src', 'data', 'art.js');

// Every art path the cards name, and which of those files exist (so the game shows Art Pending, without a
// failed request, for the rest). Rebuild after adding art.
export function artList(data) {
  const paths = data.cards.flatMap((c) => (c.forms ? c.forms.map((f) => f.art) : [c.art, c.campaignCreature?.art])).filter(Boolean);
  return [...new Set(paths)].filter((p) => existsSync(join(ROOT, p))).sort();
}
export function buildArt(data) {
  return `// GENERATED by tools/buildcards.mjs: the card art files that exist in assets/cards/. Rebuild after adding art.

export const ART = new Set(${JSON.stringify(artList(data), null, 2)});
`;
}

// Every problem with the data, as plain sentences.
export function validate(data) {
  const out = [];
  const ops = (where, list, heldOrPassive = false) => {
    for (const o of list ?? []) {
      if (heldOrPassive) continue;
      if (!EFFECT_OPS[o.op]) out.push(`${where}: unknown op "${o.op}"`);
      if (o.to && !EFFECT_TARGETS[o.to]) out.push(`${where}: unknown target "${o.to}"`);
    }
  };
  const spec = (where, t) => { if (t && !TARGET_SPECS[t]) out.push(`${where}: unknown target spec "${t}"`); };
  // A trigger: approved, its target and ops known; a Rally names its group; a choose-one trigger has 2 or more modes.
  const trig = (where, t) => {
    if (!TRIGGERS[t.on]) out.push(`${where}: trigger "${t.on}" isn't approved`);
    if (t.on === 'rally' && !Object.keys(t.group ?? {}).length) out.push(`${where}: a Rally trigger names its group`);
    if (t.choose) {
      if (t.on !== 'summon' || t.choose.length < 2) out.push(`${where}: "choose one" is an On Summon with 2 or more modes`);
      for (const m of t.choose) { spec(where, m.target); ops(where, m.ops); }
    } else { spec(where, t.target); ops(where, t.ops); }
  };
  const ids = new Set();
  for (const c of data.cards) {
    if (ids.has(c.id)) out.push(`${c.id}: duplicate id`);
    ids.add(c.id);
    if (c.cardType === 'Character' || c.cardType === 'Monster') {
      const [lo, hi] = SERIES_RANGE[c.series] ?? [];
      if (lo === undefined) out.push(`${c.id}: unknown series ${c.series}`);
      const levels = c.forms.flatMap((f) => Object.keys(f.levels).map(Number)).sort((a, b) => a - b);
      const want = Array.from({ length: hi - lo + 1 }, (_, i) => lo + i);
      if (levels.join() !== want.join()) out.push(`${c.id}: Levels ${levels} should be ${want}`);
      // Stage P: every series names its Prime Level (Legendaries are always Prime).
      if (c.series !== 'Legendary' && !(c.prime >= lo && c.prime <= hi)) out.push(`${c.id}: its Prime Level (${c.prime}) should be one of ${want}`);
      if (c.cardType === 'Character' && (!c.traits?.class || !c.traits?.race)) out.push(`${c.id}: a Character needs a Class and a Race`);
      // (Stage A, Elliott, 18 November 2026: a Character series is one person, with a first name all three forms share.)
      if (c.cardType === 'Character' && !c.firstName) out.push(`${c.id}: a Character needs a first name`);
      if (c.cardType === 'Monster' && c.firstName) out.push(`${c.id}: Monsters keep their descriptive names`);
      if (c.cardType === 'Monster' && !c.traits?.kind) out.push(`${c.id}: a Monster needs a Kind`);
      for (const f of c.forms) {
        const primes = [f.prime, ...Object.values(f.levels).map((e) => e.prime)].filter(Boolean);
        for (const k of [f.keywords, ...primes.map((x) => x.keywords)].flatMap((x) => Object.keys(x ?? {}))) if (!KEYWORDS[k]) out.push(`${f.id}: keyword "${k}" isn't approved`);
        for (const t of [f.trigger, ...Object.values(f.levels).map((e) => e.trigger), ...primes.map((x) => x.trigger)].filter(Boolean)) trig(f.id, t);
        // (Stage N: a Prime line at a Level belongs to the Prime Level only.)
        for (const [lv, e] of Object.entries(f.levels)) if (e.prime && Number(lv) !== c.prime) out.push(`${f.id}: Level ${lv} has "Prime:" lines but the Prime Level is ${c.prime}`);
        if (primes.some((x) => x.chooseBoth) && !f.trigger?.choose) out.push(`${f.id}: "Prime: Choose both" needs a choose-one On Summon`);
      }
    }
    if (c.cardType === 'Action') for (const [m, x] of Object.entries(c.modes)) { spec(`${c.id} ${m}`, x.target); ops(`${c.id} ${m}`, x.ops); }
    if (c.cardType === 'Event') { spec(c.id, c.target); ops(c.id, c.ops); ops(`${c.id} Favour`, c.favour?.ops); }
    if (c.cardType === 'Item' && c.kind === 'Consumed') { spec(c.id, c.target); ops(c.id, c.ops); }
    if (c.cardType === 'Campaign') {
      spec(c.id, c.order.target); ops(`${c.id} Order`, c.order.ops);
      // Stage N: every Campaign has a length; its Campaign Creature a Level (Side-Quest 4, mid-length 6, long 8).
      if (!CAMPAIGN_LENGTHS[c.length]) out.push(`${c.id}: its length should be one of ${Object.keys(CAMPAIGN_LENGTHS).join(', ')}`);
      else if (c.campaignCreature.level !== CAMPAIGN_LENGTHS[c.length]) out.push(`${c.id}: a ${c.length} Campaign's Creature is Level ${CAMPAIGN_LENGTHS[c.length]}`);
      for (const k of Object.keys(c.campaignCreature.keywords ?? {})) if (!KEYWORDS[k]) out.push(`${c.id}: keyword "${k}" isn't approved`);
      if (c.campaignCreature.trigger) trig(c.id, c.campaignCreature.trigger);
    }
    // Stage R: a Legendary's own Location: 3 lanes, no countdown, a negative passive; its Legendary names it back.
    if (c.cardType === 'Location' && c.legendaryOf) {
      const owner = data.cards.find((x) => x.id === c.legendaryOf);
      if (owner?.series !== 'Legendary' || owner.location !== c.id) out.push(`${c.id}: its Legendary (${c.legendaryOf}) should name it as its location`);
      if (c.width !== 3 || c.rounds !== null) out.push(`${c.id}: a Legendary's Location is 3 lanes wide with no countdown`);
      if (!c.passive.ops.every((o) => o.amount < 0 || o.op === 'duskDamage')) out.push(`${c.id}: a Legendary's Location has a negative passive`);
    }
    if (c.series === 'Legendary' && c.location && !data.cards.some((x) => x.id === c.location && x.legendaryOf === c.id)) out.push(`${c.id}: its Location ${c.location} is missing`);
  }
  const ownLocations = new Set(data.cards.filter((c) => c.legendaryOf).map((c) => c.id));
  for (const [name, d] of Object.entries(data.decks)) for (const x of d.cards) if (!ids.has(x.id)) out.push(`deck ${name}: unknown card ${x.id}`);
  for (const [name, d] of Object.entries(data.decks)) for (const x of d.cards) if (ownLocations.has(x.id)) out.push(`deck ${name}: ${x.id} is a Legendary's own Location, never in a deck`);
  return out;
}

// A Level with lines of its own: its own trigger, or (stage N) "Prime:" lines at the Prime Level.
const hasOwnLines = (e) => !!(e.trigger || e.prime);

// The generated wording for every card, in the same shape as the text in cards.json.
export function generateText(c) {
  switch (c.cardType) {
    case 'Character': case 'Monster':
      return {
        forms: c.forms.map((f) => ({
          id: f.id,
          text: creatureLines(f.keywords, f.trigger, f.prime),
          levels: Object.fromEntries(Object.entries(f.levels).filter(([, e]) => hasOwnLines(e)).map(([lv, e]) => [lv, creatureLines(f.keywords, e.trigger ?? f.trigger, e.prime ?? f.prime)])),
        })),
      };
    case 'Action': return { modes: Object.fromEntries(Object.entries(c.modes).map(([m, x]) => [m, effectText(x.ops, x.target)])) };
    case 'Event': return { text: effectText(c.ops, c.target), favour: effectText(c.favour.ops, c.target) };
    case 'Item': return { text: c.kind === 'Held' ? heldText(c.ops) : effectText(c.ops, c.target) };
    case 'Location': return { text: passiveText(c.passive.ops) };
    case 'Campaign': return { quest: questText(c.quest), order: effectText(c.order.ops, c.order.target), campaignCreature: creatureLines(c.campaignCreature.keywords, c.campaignCreature.trigger) };
    default: throw new Error(`Unknown card type ${c.cardType}`);
  }
}
// The approved text from cards.json, in the same shape.
export function approvedText(c) {
  switch (c.cardType) {
    case 'Character': case 'Monster':
      return { forms: c.forms.map((f) => ({ id: f.id, text: f.text, levels: Object.fromEntries(Object.entries(f.levels).filter(([, e]) => hasOwnLines(e)).map(([lv, e]) => [lv, e.text])) })) };
    case 'Action': return { modes: Object.fromEntries(Object.entries(c.modes).map(([m, x]) => [m, x.text])) };
    case 'Event': return { text: c.text, favour: c.favour.text };
    case 'Item': return { text: c.text };
    case 'Location': return { text: c.text };
    case 'Campaign': return { quest: c.quest.text, order: c.order.text, campaignCreature: c.campaignCreature.text };
    default: throw new Error(`Unknown card type ${c.cardType}`);
  }
}

// The card definitions the engine plays with, carrying the generated wording.
function withGeneratedText(c) {
  const g = generateText(c);
  const x = structuredClone(c);
  switch (c.cardType) {
    case 'Character': case 'Monster':
      x.forms.forEach((f, i) => {
        // (Stage A: a Character's name is "Ilyra, the Thornwood Pathfinder"; the card face shows the first name, with
        // its title on a smaller line beneath. Everything that names it in words uses the whole name.)
        if (c.firstName) Object.assign(f, { firstName: c.firstName, title: `the ${f.name}`, name: `${c.firstName}, the ${f.name}` });
        f.text = g.forms[i].text;
        for (const [lv, lines] of Object.entries(g.forms[i].levels)) f.levels[lv].text = lines;
      });
      break;
    case 'Action': for (const m of Object.keys(x.modes)) x.modes[m].text = g.modes[m]; break;
    case 'Event': x.text = g.text; x.favour.text = g.favour; break;
    case 'Item': case 'Location': x.text = g.text; break;
    case 'Campaign': x.quest.text = g.quest; x.order.text = g.order; x.campaignCreature.text = g.campaignCreature; break;
    default: break;
  }
  return x;
}

export function build(data) {
  const problems = validate(data);
  if (problems.length) throw new Error(`docs/cards.json has problems:\n  ${problems.join('\n  ')}`);
  const cards = data.cards.map(withGeneratedText);
  const decks = Object.fromEntries(Object.entries(data.decks).map(([k, d]) => [k, { name: d.name, cards: d.cards }]));
  return `// GENERATED by tools/buildcards.mjs from docs/cards.json. Don't edit by hand: edit docs/cards.json and rebuild.
// Card wording here is generated from the templates in src/engine/wording.js.

export const CARDS = ${JSON.stringify(cards, null, 2)};

export const DECKS = ${JSON.stringify(decks, null, 2)};

// The first deck as 40 card ids (both players use a copy).
export const FIRST_DECK = DECKS.first.cards.flatMap(({ id, copies }) => Array(copies).fill(id));
`;
}

// Stage A: the art data, recorded from the art itself (never hand-typed). Every card (and Campaign Creature) with
// art gets artFull (its full-art scene in assets/cards-v3/, 1536 × 1024) and cardX (the centre of its 5:7 card crop,
// from assets/cards-v3/crops.json; tools/artcrops.py cuts the crops). Locations also get tileX and tileY, the
// point a placed tile is drawn around (assets/cards-v3/tiles.json).
const ART_SRC = join(ROOT, 'assets', 'cards-v3');
export function syncArt(data) {
  const crops = JSON.parse(readFileSync(join(ART_SRC, 'crops.json'), 'utf8'));
  const tiles = JSON.parse(readFileSync(join(ART_SRC, 'tiles.json'), 'utf8'));
  const problems = [];
  // (The new keys go straight after "art", so the file reads in order.)
  const withArt = (o, extra) => {
    const out = {};
    for (const [k, v] of Object.entries(o)) {
      if (k === 'artFull' || k === 'cardX' || k === 'tileX' || k === 'tileY') continue;
      out[k] = v;
      if (k === 'art') Object.assign(out, extra);
    }
    return out;
  };
  const one = (o, isLocation = false) => {
    if (!o?.art) return o;
    const id = o.art.split('/').pop().replace(/\.jpg$/, '');
    if (!crops[id]) { problems.push(`${id}: no crop centre in assets/cards-v3/crops.json`); return o; }
    const extra = { artFull: `assets/cards-v3/${id}.jpg`, cardX: crops[id].cardX };
    if (isLocation) {
      if (!tiles[id]) problems.push(`${id}: no tile focus in assets/cards-v3/tiles.json`);
      else Object.assign(extra, { tileX: tiles[id].tileX, tileY: tiles[id].tileY });
    }
    return withArt(o, extra);
  };
  data.cards = data.cards.map((c) => {
    let x = one(c, c.cardType === 'Location');
    if (x.forms) x = { ...x, forms: x.forms.map((f) => one(f)) };
    if (x.campaignCreature) x = { ...x, campaignCreature: one(x.campaignCreature) };
    return x;
  });
  if (problems.length) throw new Error(`The art data has problems:\n  ${problems.join('\n  ')}`);
  return data;
}
export const cardsJsonText = (data) => `${JSON.stringify(data, null, 2)}\n`;

export const loadCardsJson = () => JSON.parse(readFileSync(SRC, 'utf8'));

if (process.argv[1] && import.meta.url.endsWith(process.argv[1].split('/').pop())) {
  const data = syncArt(loadCardsJson());
  const js = build(data);
  const art = buildArt(data);
  const json = cardsJsonText(data);
  if (process.argv.includes('--check')) {
    const stale = [[OUT, js], [ART_OUT, art], [SRC, json]].filter(([f, want]) => !existsSync(f) || readFileSync(f, 'utf8') !== want);
    if (stale.length) { console.error('docs/cards.json\'s art data or src/data is out of date: run node tools/buildcards.mjs'); process.exit(1); }
    console.log('src/data/cards.js and src/data/art.js are up to date.');
  } else {
    writeFileSync(SRC, json);
    writeFileSync(OUT, js);
    writeFileSync(ART_OUT, art);
    console.log(`Wrote src/data/cards.js (${data.cards.length} cards) and src/data/art.js (${artList(data).length} images).`);
  }
}
